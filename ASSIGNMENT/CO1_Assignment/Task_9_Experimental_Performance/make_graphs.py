import csv, math, os
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
R = os.path.join(os.path.dirname(__file__), "..")
rows = list(csv.DictReader(open(os.path.join(R, "Task_8_Implementation_Testing", "results.csv"))))
G = os.path.join(R, "Report", "Tables_and_Graphs")
def get(alg, case, col):
    return [(int(r["n"]), float(r[col])) for r in rows if r["algorithm"]==alg and r["case"]==case]
cols = {"Linear":"tab:red","Binary":"tab:blue","Hash":"tab:green"}
def plot(col, case, ylabel, title, fname, theory=None):
    plt.figure(figsize=(7,4.6))
    for a in cols:
        xs, ys = zip(*get(a, case, col)); plt.plot(xs, ys, "o-", color=cols[a], label=a)
    plt.xscale("log"); plt.yscale("log"); plt.xlabel("n (records)"); plt.ylabel(ylabel)
    plt.title(title); plt.grid(True, which="both", alpha=.3); plt.legend(); plt.tight_layout()
    plt.savefig(os.path.join(G, fname), dpi=140); plt.close()
for case in ("best","average","worst"):
    plot("comparisons", case, "comparisons (basic operations)", f"Comparisons vs n - {case} case", f"comparisons_{case}.png")
    plot("time_per_search_us", case, "time per search (µs)", f"Search time vs n - {case} case", f"time_{case}.png")
# preprocessing
plt.figure(figsize=(7,4.6))
for a in ("Binary","Hash"):
    xs, ys = zip(*get(a,"average","preprocessing_s")); plt.plot(xs, ys, "o-", color=cols[a], label=("Sort (for Binary)" if a=="Binary" else "Build hash index"))
plt.xscale("log"); plt.yscale("log"); plt.xlabel("n"); plt.ylabel("preprocessing time (s)"); plt.title("Preprocessing cost vs n")
plt.grid(True, which="both", alpha=.3); plt.legend(); plt.tight_layout(); plt.savefig(os.path.join(G,"preprocessing.png"), dpi=140); plt.close()
# theory vs experiment (average case time normalised at n=1000)
plt.figure(figsize=(11,4))
specs = [("Linear","O(n)",lambda n:n),("Binary","O(log n)",lambda n:math.log2(n)),("Hash","O(1)",lambda n:1)]
for i,(a,lab,f) in enumerate(specs):
    plt.subplot(1,3,i+1)
    xs, ys = zip(*get(a,"average","time_per_search_us"))
    plt.plot(xs, ys, "o-", color=cols[a], label="measured")
    k = ys[0]/f(xs[0]); plt.plot(xs, [k*f(x) for x in xs], "k--", label=f"{lab} fit @ n=1000")
    plt.xscale("log"); plt.yscale("log"); plt.title(f"{a}: measured vs {lab}"); plt.xlabel("n"); plt.ylabel("µs / search"); plt.grid(True, which="both", alpha=.3); plt.legend(fontsize=8)
plt.tight_layout(); plt.savefig(os.path.join(G,"theory_vs_experiment.png"), dpi=140); plt.close()
# Task 12 : cumulative daily cost
pre = {a: get(a,"average","preprocessing_s")[-1][1] for a in cols}
avg = {a: get(a,"average","time_per_search_us")[-1][1]*1e-6 for a in cols}
Q = 50000*24
plt.figure(figsize=(7,4.6))
import numpy as np
q = np.logspace(0, 7, 200)
for a in cols: plt.plot(q, pre[a] + q*avg[a], color=cols[a], label=a)
plt.axvline(Q, color="gray", ls=":", label="1.2 M searches/day"); plt.axvline(50000, color="gray", ls="--", label="50 k searches/hour")
plt.xscale("log"); plt.yscale("log"); plt.xlabel("searches served after one daily rebuild"); plt.ylabel("total CPU time (s)")
plt.title("n = 1,000,000: preprocessing + searching"); plt.grid(True, which="both", alpha=.3); plt.legend(); plt.tight_layout()
plt.savefig(os.path.join(G,"task12_total_cost.png"), dpi=140); plt.close()
# markdown tables
def table(case):
    L = [f"### {case.capitalize()} case", "", "| n | Linear cmp | Binary cmp | Hash cmp | Linear µs | Binary µs | Hash µs |", "|---:|---:|---:|---:|---:|---:|---:|"]
    for n in (1000,10000,100000,1000000):
        g = lambda a,c: [r for r in rows if int(r["n"])==n and r["algorithm"]==a and r["case"]==case][0][c]
        L.append(f"| {n:,} | {float(g('Linear','comparisons')):,.1f} | {float(g('Binary','comparisons')):,.2f} | {float(g('Hash','comparisons')):.2f} | {float(g('Linear','time_per_search_us')):,.2f} | {float(g('Binary','time_per_search_us')):.2f} | {float(g('Hash','time_per_search_us')):.2f} |")
    return "\n".join(L)
pt = ["### Preprocessing cost", "", "| n | Linear | Sort (Binary) | Build hash index |", "|---:|---:|---:|---:|"]
for n in (1000,10000,100000,1000000):
    g = lambda a: [r for r in rows if int(r["n"])==n and r["algorithm"]==a and r["case"]=="average"][0]["preprocessing_s"]
    pt.append(f"| {n:,} | 0 | {float(g('Binary')):.4f} s | {float(g('Hash')):.4f} s |")
md = "# Experimental results (auto-generated by make_graphs.py)\n\n" + "\n\n".join(table(c) for c in ("best","average","worst")) + "\n\n" + "\n".join(pt) + "\n"
open(os.path.join(R,"Task_9_Experimental_Performance","results_tables.md"),"w").write(md)
open(os.path.join(G,"results_tables.md"),"w").write(md)
